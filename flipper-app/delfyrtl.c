static void delfy_start_capture(delfyRTL* app, bool grab) {
    FURI_LOG_D(TAG, __func__);
    int ch = delfy_def_ch();
    if(app->selectedWifi >= 0 && app->selectedWifi < app->wifiCount) {
        ch = app->wifiList[app->selectedWifi].chanel;
    }
    char cmd[64];
    if(grab && app->selectedWifi >= 0 && app->selectedWifi < app->wifiCount) {
        // HSGRAB wants the BSSID as 12 hex chars (no colons).
        char hex[13];
        int j = 0;
        const char* b = app->wifiList[app->selectedWifi].APbssid;
        for(int i = 0; b[i] && j < 12; i++) {
            if(b[i] != ':') hex[j++] = b[i];
        }
        hex[j] = '\0';
        if(j != 12) {   // unpadded/malformed MAC -> refuse instead of sending garbage
            snprintf(message, sizeof(message), "Bad BSSID - rescan");
            snprintf(popupHeader, sizeof(popupHeader), "ERROR");
            scene_manager_next_scene(app->scene_manager, popupScene);
            return;
        }
        snprintf(cmd, sizeof(cmd), "HSGRAB %d %s 20\n", ch, hex);
    } else {
        snprintf(cmd, sizeof(cmd), "CAPTURE %d 20\n", ch);
    }
    uart_helper_send(app->uart_helper, cmd, strlen(cmd));
    // Result is shown when HSDONE arrives (uart_process_line -> popupScene).
    { char b[48]; snprintf(b, sizeof(b), "Capturing on ch %d...", ch); delfy_busy_ex(app, "Handshake", b, 20); }
}

