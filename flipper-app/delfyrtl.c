int32_t delfyRTL_app(void* p) {
    FURI_LOG_D(TAG, __func__);
    UNUSED(p);

    delfyRTL* app = app_alloc();
    delfy_settings_load();
    {
        // Session id = app-launch timestamp; scan results land in sessions/<id>/.
        DateTime dt;
        furi_hal_rtc_get_datetime(&dt);
        snprintf(
            delfy_session_id,
            sizeof(delfy_session_id),
            "%04d-%02d-%02d_%02d-%02d-%02d",
            dt.year,
            dt.month,
            dt.day,
            dt.hour,
            dt.minute,
            dt.second);
    }
    Expansion* expansion = furi_record_open(RECORD_EXPANSION);
    expansion_disable(expansion);
    if(!furi_hal_power_is_otg_enabled()) furi_hal_power_enable_otg();
    Gui* gui = furi_record_open(RECORD_GUI);
    view_dispatcher_attach_to_gui(app->view_dispatcher, gui, ViewDispatcherTypeFullscreen);
    scene_manager_next_scene(app->scene_manager, mainMenuScene);
    view_dispatcher_run(app->view_dispatcher);

    app_free(app);
    expansion_enable(expansion);
    furi_record_close(RECORD_EXPANSION);

    return 0;
}
