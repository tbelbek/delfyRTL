bool parse_mac(const char* mac_str, uint8_t* out_bytes) {
    if(!mac_str || !out_bytes) return false;

    char mac_copy[18];
    strncpy(mac_copy, mac_str, sizeof(mac_copy));
    mac_copy[17] = '\0'; // Garantizar null terminator

    char* token = strtok(mac_copy, ":");
    int i = 0;

    while(token != NULL && i < 6) {
        char* endptr;
        long value = strtol(token, &endptr, 16);

        if(*endptr != '\0' || value < 0 || value > 255) {
            return false; // Error en la conversión
        }

        out_bytes[i++] = (uint8_t)value;
        token = strtok(NULL, ":");
    }

    return i == 6;
}

// --- P5 handshake capture: the board streams captured EAPOL frames as
// `HSFRAME:<hex>` lines (see RTL8720dn-firmware.ino CAPTURE/HSGRAB). We buffer them
// and rebuild a LINKTYPE_IEEE802_11 pcap on the SD card at `/ext/delfy/hs.pcap`,
// ready for `hcxpcapngtool -o x.hc22000` -> `hashcat -m 22000`. ---
#define HS_FRAME_MAX  256
#define HS_MAX_FRAMES 16
static uint8_t hs_frames[HS_MAX_FRAMES][HS_FRAME_MAX];
static uint16_t hs_lens[HS_MAX_FRAMES];
static uint16_t hs_count = 0;
static int hs_channel = 0;
static char popupHeader[20] = "ERROR";

static int hs_hexval(char c) {
    if(c >= '0' && c <= '9') return c - '0';
    if(c >= 'a' && c <= 'f') return c - 'a' + 10;
    if(c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

static void hs_put_le32(uint8_t* p, uint32_t v) {
    p[0] = v & 0xFF;
    p[1] = (v >> 8) & 0xFF;
    p[2] = (v >> 16) & 0xFF;
    p[3] = (v >> 24) & 0xFF;
}

static void hs_write_pcap(uint16_t* out_frames) {
    Storage* storage = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(storage, "/ext/delfy");
    File* file = storage_file_alloc(storage);
    uint16_t written = 0;
    if(storage_file_open(file, "/ext/delfy/hs.pcap", FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
        uint8_t hdr[24] = {0};
        hs_put_le32(hdr + 0, 0xA1B2C3D4); // pcap magic (LE -> d4 c3 b2 a1)
        hs_put_le32(hdr + 4, 0x00040002); // version major=2 (u16), minor=4 (u16)
        hs_put_le32(hdr + 8, 0); // thiszone
        hs_put_le32(hdr + 12, 0); // sigfigs
        hs_put_le32(hdr + 16, 65535); // snaplen
        hs_put_le32(hdr + 20, 105); // LINKTYPE_IEEE802_11 (802.11, no FCS)
        storage_file_write(file, hdr, sizeof(hdr));
        for(uint16_t i = 0; i < hs_count && i < HS_MAX_FRAMES; i++) {
            if(hs_lens[i] == 0) continue;
            uint8_t rec[16];
            uint32_t ts = furi_get_tick();
            hs_put_le32(rec + 0, ts / 1000);
            hs_put_le32(rec + 4, (ts % 1000) * 1000);
            hs_put_le32(rec + 8, hs_lens[i]);
            hs_put_le32(rec + 12, hs_lens[i]);
            storage_file_write(file, rec, sizeof(rec));
            storage_file_write(file, hs_frames[i], hs_lens[i]);
            written++;
        }
        storage_file_close(file);
    }
    storage_file_free(file);
    furi_record_close(RECORD_STORAGE);
    if(out_frames) *out_frames = written;
}

// Quality engine: classify the buffered EAPOL-Key frames as M1..M4 (EAPOL-Key Key Info is
// big-endian: Install=bit6, ACK=bit7, MIC=bit8, Secure=bit9) and say if it's crackable.
static void hs_quality(char* out, size_t cap) {
    bool m[5] = {false};
    for(uint16_t i = 0; i < hs_count && i < HS_MAX_FRAMES; i++) {
        const uint8_t* b = hs_frames[i];
        uint16_t len = hs_lens[i];
        unsigned e;
        if(len >= 32 && b[30] == 0x88 && b[31] == 0x8e) e = 32;
        else if(len >= 34 && b[32] == 0x88 && b[33] == 0x8e) e = 34;
        else continue;
        if(e + 99 > len) continue;
        if(b[e + 1] != 3 || b[e + 4] != 2) continue; // EAPOL-Key, RSN
        uint16_t ki = ((uint16_t)b[e + 5] << 8) | b[e + 6];
        bool ack = ki & 0x0080, mic = ki & 0x0100, sec = ki & 0x0200;
        if(ack && !mic) m[1] = true;
        else if(!ack && mic && !sec) m[2] = true;
        else if(ack && mic && sec) m[3] = true;
        else if(!ack && mic && sec) m[4] = true;
    }
    bool crackable = (m[1] && m[2]) || (m[2] && m[3]);
    snprintf(
        out,
        cap,
        "%s%s%s%s%s",
        m[1] ? "M1 " : "",
        m[2] ? "M2 " : "",
        m[3] ? "M3 " : "",
        m[4] ? "M4 " : "",
        crackable ? "OK" : (m[1] ? "M1 only" : "incomplete"));
}

// E: write a small audit summary next to the capture.
static void audit_write_json(const char* kind, int frames) {    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/delfy");
    File* f = storage_file_alloc(st);
    if(storage_file_open(f, "/ext/delfy/audit.json", FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
        char buf[256];
        int n = snprintf(
            buf,
            sizeof(buf),
            "{\"ssid\":\"%s\",\"bssid\":\"%s\",\"channel\":%d,\"security\":%d,\"kind\":\"%s\",\"frames\":%d}\n",
            audit_ssid,
            audit_bssid,
            audit_ch,
            audit_sec,
            kind,
            frames);
        if(n < 0) n = 0;
        if(n >= (int)sizeof(buf)) n = sizeof(buf) - 1;
        storage_file_write(f, buf, n);
        storage_file_close(f);
    }
    storage_file_free(f);
    furi_record_close(RECORD_STORAGE);
    audit_mode = false;
}

// Evidence pack: dump collected PMKID WPA*01* lines to /ext/delfy/pmkid.22000.
static void write_wpa_file(void) {
    if(wpa_lines[0] == '\0') return;
    Storage* st = furi_record_open(RECORD_STORAGE);
    storage_common_mkdir(st, "/ext/delfy");
    File* f = storage_file_alloc(st);
    if(storage_file_open(f, "/ext/delfy/pmkid.22000", FSAM_WRITE, FSOM_CREATE_ALWAYS)) {
        storage_file_write(f, wpa_lines, strlen(wpa_lines));
        storage_file_close(f);
    }
    storage_file_free(f);
    furi_record_close(RECORD_STORAGE);
}

