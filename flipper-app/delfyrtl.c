// D: PMF/SAE estimate from the Realtek security bitmask (mirrors 5Ghost).
// WPA3 mandates PMF; AES_CMAC is the BIP cipher. A WPA2 AP with PMF-optional isn't
// distinguishable from the bitmask alone -> run "PMF/WPA3 scan" for the precise RSN-IE answer.
static const char* delfy_pmf_tag(int security) {
    if(security & WPA3_SECURITY) return "PMF!";
    if(security & AES_CMAC_ENABLED) return "PMF";
    return "";
}

