static delfyRTL* app_alloc() {
    FURI_LOG_D(TAG, __func__);
    delfyRTL* app = malloc(sizeof(delfyRTL));
    app->ssidAPLength = 32;
    //app->ssidAPLength = 0;
    app->captivePortal = 0;
    app->deauthReason = 2;
    app->mac_type = 1; // default: random AP MAC
    app->securityAP = 0;
    app->channelAP = 9;
    app->ssidAP = malloc(app->ssidAPLength);
    strcpy(app->ssidAP, "Free_Wifi");
    app->passwordAPLength = 64;
    app->passwordAP = malloc(app->passwordAPLength);
    strcpy(app->passwordAP, "password123");
    app->selectedWifi = 0;
    app->wifiCount = 0;
    app->menuIndex = 0;
    app->submenuIndex = 0;
    app->fw_version[0] = '\0';
    app->fw_caps[0] = '\0';
    app->bleAdvHex[0] = '\0';
    app->ibeaconUuid[0] = '\0';
    app->scene_manager = scene_manager_alloc(&delfyRTL_scene_manager_handlers, app);
    app->view_dispatcher = view_dispatcher_alloc();
    // Default AP MAC = random (locally administered)
    {
        unsigned char random_mac[6];
        generate_mac_address(random_mac);
        snprintf(
            app->customMac,
            sizeof(app->customMac),
            "%02X:%02X:%02X:%02X:%02X:%02X",
            random_mac[0],
            random_mac[1],
            random_mac[2],
            random_mac[3],
            random_mac[4],
            random_mac[5]);
    }
    parse_mac(app->customMac, app->byte_input_store);

    view_dispatcher_set_event_callback_context(app->view_dispatcher, app);
    view_dispatcher_set_custom_event_callback(app->view_dispatcher, delfyRTL_custom_callback);
    view_dispatcher_set_navigation_event_callback(
        app->view_dispatcher, delfyRTL_back_event_callback);

    app->menu = menu_alloc();
    view_dispatcher_add_view(app->view_dispatcher, mainMenuView, menu_get_view(app->menu));

    app->submenu = submenu_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, scannedWifisView, submenu_get_view(app->submenu));
    view_dispatcher_add_view(app->view_dispatcher, beaconListView, submenu_get_view(app->submenu));

    app->text_input = text_input_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, bssidTextInputView, text_input_get_view(app->text_input));
    view_dispatcher_add_view(
        app->view_dispatcher, apNameTextInputView, text_input_get_view(app->text_input));
    view_dispatcher_add_view(
        app->view_dispatcher, apPasswordTextInputView, text_input_get_view(app->text_input));

    app->loading = loading_alloc();
    view_dispatcher_add_view(app->view_dispatcher, loadingView, loading_get_view(app->loading));

    app->widget = widget_alloc();
    // The widget view is registered for several scenes (wifiInfo/evilCreds/beaconInfo/...) and
    // now also receives input (C1 portal picker). Without a context those callbacks get NULL as
    // their context and dereferencing it hard-crashes the Flipper - which is exactly what
    // happened the first time LEFT/RIGHT was pressed on the Trap screen.
    view_set_context(widget_get_view(app->widget), app);
    view_dispatcher_add_view(app->view_dispatcher, wifiInfoView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, evilCredsView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, beaconInfoView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, helpView, widget_get_view(app->widget));
    view_dispatcher_add_view(app->view_dispatcher, pmfView, widget_get_view(app->widget));
    view_dispatcher_add_view(
        app->view_dispatcher, toolsListView, submenu_get_view(app->submenu));

    app->variableList = variable_item_list_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, configAttackView, variable_item_list_get_view(app->variableList));
    view_dispatcher_add_view(
        app->view_dispatcher, configAPView, variable_item_list_get_view(app->variableList));
    view_dispatcher_add_view(
        app->view_dispatcher, settingsView, variable_item_list_get_view(app->variableList));

    app->byteInput = byte_input_alloc();
    view_dispatcher_add_view(
        app->view_dispatcher, aPmacAddresView, byte_input_get_view(app->byteInput));

    app->popup = popup_alloc();
    view_dispatcher_add_view(app->view_dispatcher, popupView, popup_get_view(app->popup));

    // Card-grid main menu
    app->cardView = view_alloc();
    view_allocate_model(app->cardView, ViewModelTypeLockFree, 1); // enable view_commit_model refresh
    view_set_context(app->cardView, app);
    view_set_draw_callback(app->cardView, card_menu_draw);
    view_set_input_callback(app->cardView, card_menu_input);
    view_dispatcher_add_view(app->view_dispatcher, cardMenuView, app->cardView);

    app->chanMapView = view_alloc();
    view_allocate_model(app->chanMapView, ViewModelTypeLocking, sizeof(ChanModel));
    view_set_context(app->chanMapView, app);
    view_set_draw_callback(app->chanMapView, channel_map_draw);
    view_set_input_callback(app->chanMapView, channel_map_input);
    view_dispatcher_add_view(app->view_dispatcher, channelMapView, app->chanMapView);

    // Animated "working" screen (operation name + spinner)
    app->busyView = view_alloc();
    view_allocate_model(app->busyView, ViewModelTypeLockFree, sizeof(BusyModel));
    view_set_context(app->busyView, app);
    view_set_draw_callback(app->busyView, busy_view_draw);
    view_dispatcher_add_view(app->view_dispatcher, busyView, app->busyView);
    app->busyTimer = furi_timer_alloc(busy_timer_cb, FuriTimerTypePeriodic, app);
    app->karmaTimer = furi_timer_alloc(karma_timer_cb, FuriTimerTypePeriodic, app);
    app->scriptTimer = furi_timer_alloc(script_timer_cb, FuriTimerTypePeriodic, app);

    app->uart_helper = uart_helper_alloc();
    uart_helper_set_baud_rate(app->uart_helper, DEVICE_BAUDRATE);
    uart_helper_set_delimiter(app->uart_helper, LINE_DELIMITER, INCLUDE_LINE_DELIMITER);
    uart_helper_set_callback(app->uart_helper, uart_process_line, app);
    uart_helper_send(app->uart_helper, "HELLO\n", 6); // A: ask the board to advertise caps

    app->timer = furi_timer_alloc(animation_timer_callback, FuriTimerTypePeriodic, app);
    return app;
}

