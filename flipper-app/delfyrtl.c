// Shows the operation name + a spinner so a blocking board op is visibly alive,
// instead of the static popup with the idle dolphin icon. Driven by a periodic timer
// that posts a GUI-thread custom event (view model updates must run on the GUI thread).
static void busy_view_draw(Canvas* canvas, void* model) {
    BusyModel* m = model;
    canvas_clear(canvas);
    canvas_set_font(canvas, FontPrimary);
    canvas_draw_str_aligned(canvas, 64, 10, AlignCenter, AlignTop, popupHeader);
    canvas_set_font(canvas, FontSecondary);
    canvas_draw_str_aligned(canvas, 64, 26, AlignCenter, AlignTop, message);
    if(m->remain_s > 0) {
        char t[8];
        snprintf(t, sizeof(t), "%ds", m->remain_s);
        canvas_draw_str_aligned(canvas, 126, 2, AlignRight, AlignTop, t);
    }
    static const int8_t dx[8] = {0, 8, 12, 8, 0, -8, -12, -8};
    static const int8_t dy[8] = {-12, -8, 0, 8, 12, 8, 0, -8};
    for(int i = 0; i < 8; i++) {
        int x = 64 + dx[i], y = 50 + dy[i];
        if(i == (int)(m->phase & 7)) canvas_draw_disc(canvas, x, y, 2);
        else canvas_draw_dot(canvas, x, y);
    }
}

static volatile uint32_t busy_ticks = 0;
static int busy_total_s = 0;

static void busy_timer_cb(void* context) {
    // Commit the model straight from the timer thread -- the same pattern the (working)
    // RickRoll widget animation uses. Going through view_dispatcher_send_custom_event
    // left the phase stuck, so the spinner never rotated.
    delfyRTL* app = context;
    with_view_model(
        app->busyView,
        BusyModel* m,
        {
            m->phase++;
            if(busy_total_s > 0) {   // E2: live countdown for timed operations
                int rem = busy_total_s - (int)(busy_ticks * 120 / 1000);
                m->remain_s = (rem > 0) ? (int8_t)rem : 0;
            }
        },
        true);
    // Watchdog: the board may never answer (wedged AP/capture). Without this the spinner
    // spun forever with no way out besides BACK. ~36 s at 120 ms/tick -> "Timeout" popup.
    if(++busy_ticks >= 300) {
        busy_ticks = 0;
        view_dispatcher_send_custom_event(app->view_dispatcher, DELFY_EVT_BUSY_TIMEOUT);
    }
}

static void busy_show(delfyRTL* app) {
    busy_ticks = 0;
    with_view_model(
        app->busyView,
        BusyModel* m,
        {
            m->phase = 0;
            m->remain_s = (int8_t)busy_total_s;
        },
        true);
    furi_timer_start(app->busyTimer, 120);
    view_dispatcher_switch_to_view(app->view_dispatcher, busyView);
}

void busy_scene_on_enter(void* context) {
    delfyRTL* app = context;
    busy_show(app);
}
bool busy_scene_on_event(void* context, SceneManagerEvent event) {
    delfyRTL* app = context;
    if(event.type == SceneManagerEventTypeCustom && event.event == DELFY_EVT_BUSY_TICK) {
        with_view_model(app->busyView, BusyModel* m, { m->phase++; }, true);
        return true;
    }
    if(event.type == SceneManagerEventTypeCustom && event.event == DELFY_EVT_BUSY_TIMEOUT) {
        // No board reply within the watchdog window: drop the spinner and say so instead of
        // spinning forever.
        furi_timer_stop(app->busyTimer);
        busy_active = false;
        snprintf(message, sizeof(message), "Timed out - no board reply");
        snprintf(popupHeader, sizeof(popupHeader), "Timeout");
        scene_manager_previous_scene(app->scene_manager);
        scene_manager_next_scene(app->scene_manager, popupScene);
        return true;
    }
    return false;
}
void busy_scene_on_exit(void* context) {
    delfyRTL* app = context;
    furi_timer_stop(app->busyTimer);
    busy_active = false;
}

